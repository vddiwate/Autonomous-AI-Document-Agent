from typing import List, Optional, Dict, Any
from pydantic import BaseModel, Field

class TaskItem(BaseModel):
    """Represents an individual executable task in the agent's plan."""
    id: int = Field(..., description="Unique step number, starting at 1")
    title: str = Field(..., description="Short title of the task")
    description: str = Field(..., description="Detailed instructions for what needs to be produced")
    tool: str = Field(
        default="content_generator",
        description="Tool name to handle this task (e.g., 'content_generator', 'table_generator')"
    )
    status: str = Field(default="pending", description="Status: 'pending', 'in_progress', 'completed', 'failed'")
    result: Optional[str] = Field(default=None, description="Output generated after executing this step")

class TableData(BaseModel):
    """Structured table representation for clean rendering in Word (.docx)."""
    headers: List[str] = Field(default_factory=list, description="Column header titles")
    rows: List[List[str]] = Field(default_factory=list, description="Row values")

class DocumentSection(BaseModel):
    """Represents a section of the final generated business document."""
    section_id: int
    title: str
    content: str
    table: Optional[TableData] = None
    callout: Optional[str] = None

class Plan(BaseModel):
    """Autonomous execution plan generated by the agent."""
    document_title: str = Field(..., description="Professional title of the document")
    document_type: str = Field(..., description="Type of document (e.g. Project Plan, Proposal, SOP, Architecture Design)")
    is_ambiguous: bool = Field(default=False, description="True if the user prompt had missing or conflicting details")
    assumptions: List[str] = Field(default_factory=list, description="Business/technical assumptions made to resolve ambiguity")
    tasks: List[TaskItem] = Field(default_factory=list, description="Ordered list of execution steps")
